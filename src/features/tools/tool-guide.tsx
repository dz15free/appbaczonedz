import Link from "next/link";

/* ════════════════════════════════════════════════════════════
   شرح مكتوب تحت الأداة — يجيب عن «كيف أستعملها في مراجعتي؟»

   الأداة وحدها صفحة بلا نصّ تقريباً: لا يعرف الزائر (ولا محرّك البحث
   ولا مراجع الإعلانات) ماذا يفعل بها. هذا النصّ يُرسم على الخادم مع
   الصفحة، ويختفي عند الطباعة (`no-print`).
   ════════════════════════════════════════════════════════════ */

type Block = { h: string; p?: string[]; list?: string[]; table?: { head: string[]; rows: string[][]; foot?: string[] } };

function GuideBody({ title, blocks, links }: { title: string; blocks: Block[]; links: { href: string; label: string }[] }) {
  return (
    <article className="no-print mx-auto mt-10 w-full max-w-3xl px-4 pb-12 text-right" dir="rtl">
      <h2 className="font-display text-xl font-extrabold text-text-primary">{title}</h2>
      {blocks.map((b) => (
        <section key={b.h} className="mt-6">
          <h3 className="text-base font-extrabold text-text-primary">{b.h}</h3>
          {b.p?.map((t) => (
            <p key={t.slice(0, 40)} className="mt-2 text-sm leading-7 text-text-muted">{t}</p>
          ))}
          {b.list && (
            <ul className="mt-2 list-disc space-y-1.5 pr-5 text-sm leading-7 text-text-muted">
              {b.list.map((t) => <li key={t.slice(0, 40)}>{t}</li>)}
            </ul>
          )}
          {b.table && (
            <div className="mt-3 overflow-x-auto rounded-xl border border-border">
              <table className="w-full text-sm">
                <thead className="bg-surface">
                  <tr>{b.table.head.map((c) => <th key={c} className="px-3 py-2 text-right font-extrabold">{c}</th>)}</tr>
                </thead>
                <tbody>
                  {b.table.rows.map((r) => (
                    <tr key={r.join("|")} className="border-t border-border">
                      {r.map((c, i) => <td key={i} className="px-3 py-2 text-text-muted">{c}</td>)}
                    </tr>
                  ))}
                </tbody>
                {b.table.foot && (
                  <tfoot className="border-t border-border bg-surface font-bold">
                    <tr>{b.table.foot.map((c, i) => <td key={i} className="px-3 py-2">{c}</td>)}</tr>
                  </tfoot>
                )}
              </table>
            </div>
          )}
        </section>
      ))}
      <nav aria-label="روابط مفيدة" className="mt-8 flex flex-wrap gap-x-5 gap-y-2 text-sm font-bold text-primary">
        {links.map((l) => <Link key={l.href} href={l.href}>{l.label} ←</Link>)}
      </nav>
    </article>
  );
}

