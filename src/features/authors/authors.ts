export const DEFAULT_AUTHOR = AUTHORS[0];

/** يربط اسماً محفوظاً في المقال بكاتب معروف — والأسماء العامّة تعود للافتراضي */
export function resolveAuthor(name?: string): Author {
  const n = (name ?? "").trim().toLowerCase();
  if (!n || n.includes("baczone") || n.includes("فريق")) return DEFAULT_AUTHOR;
  return AUTHORS.find((a) => a.name.toLowerCase() === n || a.slug === n) ?? DEFAULT_AUTHOR;
}

export function getAuthor(slug: string): Author | null {
  return AUTHORS.find((a) => a.slug === slug) ?? null;
}
