/** الدومين الرسميّ — يُستبدَل بمتغيّر البيئة في Vercel إن وُجد */
const FALLBACK = "https://baczone.app";

/** عنوان المنصّة بلا شرطة مائلة في آخره */
export const SITE_URL = (process.env.NEXT_PUBLIC_SITE_URL || FALLBACK).replace(/\/+$/, "");

/** رابط مطلق — Google يرفض الروابط النسبية في البيانات المنظّمة */
export function absUrl(path: string): string {
  return `${SITE_URL}${path.startsWith("/") ? path : `/${path}`}`;
}
